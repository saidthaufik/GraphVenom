def _build_atom_property_scaler() -> Tuple[Dict[str, float], Dict[str, float]]:
    mins = {k: float("inf") for k in ATOM_PROPERTY_KEYS}
    maxs = {k: float("-inf") for k in ATOM_PROPERTY_KEYS}
    for props in ATOM_PROPERTY.values():
        for k in ATOM_PROPERTY_KEYS:
            v = float(props.get(k, 0.0))
            if v < mins[k]:
                mins[k] = v
            if v > maxs[k]:
                maxs[k] = v
    for k in ATOM_PROPERTY_KEYS:
        if mins[k] == float("inf"):
            mins[k] = 0.0
            maxs[k] = 1.0
    return mins, maxs


ATOM_PROPERTY_MIN, ATOM_PROPERTY_MAX = _build_atom_property_scaler()


def atom_property_vector(atom: rdchem.Atom) -> List[float]:
    props = ATOM_PROPERTY.get(atom.GetSymbol())
    if props is None:
        return [0.0] * len(ATOM_PROPERTY_KEYS)
    values = []
    for k in ATOM_PROPERTY_KEYS:
        v = float(props.get(k, 0.0))
        min_v = ATOM_PROPERTY_MIN[k]
        max_v = ATOM_PROPERTY_MAX[k]
        if max_v == min_v:
            values.append(0.0)
        else:
            values.append((v - min_v) / (max_v - min_v))
    return values


def normalize_dict(d: Dict[str, float]) -> Dict[str, float]:
    vals = list(d.values())
    min_v, max_v = min(vals), max(vals)
    if max_v == min_v:
        return {k: 0.0 for k in d}
    return {k: (v - min_v) / (max_v - min_v) for k, v in d.items()}


