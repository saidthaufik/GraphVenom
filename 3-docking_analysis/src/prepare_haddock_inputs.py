#!/usr/bin/env python3
"""Prepare HADDOCK3 pair folders from PDB readiness checks."""

from __future__ import annotations

# Publication layout bootstrap; model equations and training parameters are unchanged.
from pathlib import Path as _PublicationPath
import sys as _publication_sys
_PUB_ROOT = next(p for p in _PublicationPath(__file__).resolve().parents if (p / ".rki-publication.json").is_file())
_publication_sys.path.insert(0, str(_PUB_ROOT / "2-machine_learning_analysis"))

import argparse
import csv
import os
import re
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_DIR = _PUB_ROOT
DEFAULT_CHECK_CSV = _PUB_ROOT / "3-docking_analysis" / "cache" / "readiness" / "all_pdb_check.csv"
DEFAULT_OUT_DIR = _PUB_ROOT / "3-docking_analysis" / "cache"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-csv", type=Path, default=DEFAULT_CHECK_CSV, help="all_pdb_check.csv from snake/check.py.")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR, help="Output root for HADDOCK pair folders.")
    parser.add_argument("--ncores", type=int, default=12, help="ncores value written into each HADDOCK config.")
    parser.add_argument("--sampling", type=int, default=100, help="rigidbody sampling value.")
    parser.add_argument("--select", type=int, default=20, help="seletop select value.")
    parser.add_argument("--force", action="store_true", help="Overwrite generated input/config files when they already exist.")
    return parser.parse_args()


def safe_name(value: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_.-]+", "_", value.strip())
    return value.strip("._") or "NA"


def read_ready_rows(check_csv: Path) -> list[dict[str, str]]:
    with check_csv.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    not_ready = [row for row in rows if row.get("dock_input_status") != "READY"]
    if not_ready:
        raise SystemExit(f"{len(not_ready)} pair(s) are not READY. Run check.py and resolve missing PDBs first.")
    return rows


def replace_chain_id(line: str, chain_id: str) -> str:
    if line.startswith(("ATOM  ", "HETATM", "TER   ")) and len(line) >= 22:
        return f"{line[:21]}{chain_id}{line[22:]}"
    return line


def write_peptide_chain_b(src: Path, dst: Path, force: bool) -> None:
    if dst.exists() and not force:
        return
    with src.open(errors="replace") as handle:
        lines = [replace_chain_id(line, "B") for line in handle]
    dst.write_text("".join(lines))


def ensure_receptor_link(src: Path, dst: Path, force: bool) -> None:
    if dst.exists() or dst.is_symlink():
        if not force:
            return
        dst.unlink()
    rel_src = os.path.relpath(src, start=dst.parent)
    dst.symlink_to(rel_src)


def write_config(path: Path, args: argparse.Namespace, peptide_len: int) -> None:
    text = f'''# HADDOCK3 protein-peptide scoring run.
# Generated by r_dock_hd/prepare_haddock_inputs.py.

run_dir = "run_peptide_score"
mode = "local"
ncores = {args.ncores}

molecules = [
  "input/receptor.pdb",
  "input/peptide_chainB.pdb"
]

[topoaa]

[rigidbody]
tolerance = 20
sampling = {args.sampling}
cmrest = true

[seletop]
select = {args.select}

[flexref]
tolerance = 20
cmrest = true
fle_sta_1 = 1
fle_end_1 = {peptide_len}
fle_seg_1 = "B"
ssdihed = "alphabeta"
mdsteps_rigid = 2000
mdsteps_cool1 = 2000
mdsteps_cool2 = 4000
mdsteps_cool3 = 4000

[caprieval]

[emref]
tolerance = 20
fle_sta_1 = 1
fle_end_1 = {peptide_len}
fle_seg_1 = "B"
ssdihed = "alphabeta"

[caprieval]
allatoms = true
'''
    path.write_text(text)


def prepare_pair(row: dict[str, str], args: argparse.Namespace) -> dict[str, str]:
    dataset = row["dataset"]
    rank = int(row["rank"])
    pep_id = row["pep_id"]
    uniprot_id = row["uniprot_id"]
    seq_pep = row["seq_pep"]
    pair_id = f"{rank:03d}__{safe_name(pep_id)}__{safe_name(uniprot_id)}"
    pair_dir = args.out_dir / dataset / "pairs" / pair_id
    input_dir = pair_dir / "input"
    input_dir.mkdir(parents=True, exist_ok=True)

    peptide_src = Path(row["peptide_pdb_path"])
    protein_src = Path(row["protein_pdb_path"])
    receptor_dst = input_dir / "receptor.pdb"
    peptide_dst = input_dir / "peptide_chainB.pdb"
    config_path = pair_dir / "haddock_peptide_score.cfg"

    ensure_receptor_link(protein_src, receptor_dst, args.force)
    write_peptide_chain_b(peptide_src, peptide_dst, args.force)
    if args.force or not config_path.exists():
        write_config(config_path, args, len(seq_pep))

    return {
        "dataset": dataset,
        "rank": str(rank),
        "pair_id": pair_id,
        "pep_id": pep_id,
        "seq_pep": seq_pep,
        "uniprot_id": uniprot_id,
        "snake_venom_protein": row["snake_venom_protein"],
        "cancer_protein": row["cancer_protein"],
        "pred_probability": row["pred_probability"],
        "vote": row["vote"],
        "consensus": row["consensus"],
        "mean_plddt": row["mean_plddt"],
        "pair_dir": str(pair_dir),
        "config": str(config_path),
        "receptor_pdb": str(receptor_dst),
        "peptide_pdb": str(peptide_dst),
        "source_receptor_pdb": str(protein_src),
        "source_peptide_pdb": str(peptide_src),
        "run_command": f"cd {pair_dir} && haddock3 haddock_peptide_score.cfg",
    }


def write_csv(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("")
        return
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def main() -> int:
    args = parse_args()
    args.check_csv = args.check_csv.resolve()
    args.out_dir = args.out_dir.resolve()
    rows = read_ready_rows(args.check_csv)

    prepared = [prepare_pair(row, args) for row in rows]
    manifest = args.out_dir / "haddock_pairs_manifest.csv"
    commands = args.out_dir / "haddock_commands.txt"
    write_csv(manifest, prepared)
    commands.write_text("\n".join(row["run_command"] for row in prepared) + "\n")

    by_dataset: dict[str, int] = {}
    for row in prepared:
        by_dataset[row["dataset"]] = by_dataset.get(row["dataset"], 0) + 1

    print("[PREPARE] HADDOCK3 pair inputs")
    print(f"Check CSV              : {args.check_csv}")
    print(f"Output dir             : {args.out_dir}")
    print(f"Pairs prepared         : {len(prepared)}")
    for dataset in sorted(by_dataset):
        print(f"  {dataset:<5}                 : {by_dataset[dataset]}")
    print(f"ncores per config      : {args.ncores}")
    print(f"rigidbody sampling     : {args.sampling}")
    print(f"seletop select         : {args.select}")
    print(f"Manifest               : {manifest}")
    print(f"Commands               : {commands}")
    print()
    print("[NEXT]")
    print("  Review manifest and then run selected commands yourself.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
